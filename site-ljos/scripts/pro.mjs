// The pro demos: whole apps on pages of their own (/demos/<name>/),
// each one entry of bundle/Demos/pro.json. Its title, its page, its
// card on /demos/, its files for the editor and to download, and the
// imports its page loads it by are all made from that entry here, so a
// second demo is an entry, its files and its app's frame (`app`), with
// no change to the build, the shell or the demos page.
//
// An entry: `name` (its route's last part), `dir` (its copied files
// under bundle/Demos), `app` (the file under bundle/Demos that runs
// them in the page's frame), `entry` (the app's root file), `upstream`
// (where the files are copied from, and what there is `leave`n out),
// the words of its page and card, `needs` (what DemoFrame needs),
// `width` and `height` (its shape), and `picture` (its pictures' name:
// `<picture>.webp` light, `<picture>-dark.webp` dark). Optional: `use`
// (a paragraph under the app on how to work it), `compact` (`width` and
// `height` of its shape on a narrow page, for an app that lays itself
// out again when it is taller than wide) and `scheme` (dark or light,
// for an app with one look; without it the pictures follow the site).
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const bundle = resolve(dirname(fileURLToPath(import.meta.url)), "../bundle");
export const demos = JSON.parse(readFileSync(join(bundle, "Demos/pro.json"), "utf8"));
export const route = (demo) => `/demos/${demo.name}/`;
export const titles = (all, after) => Object.fromEntries(all.map((demo) => [route(demo), `${demo.title}${after}`]));
export const pages = (all, after) => all.map((demo) => ({ route: route(demo), title: `${demo.title}${after}`, description: demo.description, props: { route: route(demo) } }));
// Where the built site serves a demo's files as they are: its editor
// compiles an edit against them, and a reader downloads them there.
export const sourceAt = (demo) => `demos/${demo.name}/source`;
export const targetOf = (demo) => join(bundle, "Demos", demo.dir);
export const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
// What an app runs on: its QML, its TypeScript and its assets. What
// made them (a build script, the source of a model) is left upstream,
// and so is anything outside those, such as a native crate's files.
export const shippedBy = (demo) => (path) => !demo.upstream.leave.includes(path) && (/\.(qml|ts)$/.test(path) || path.startsWith("assets/"));
// What `git ls-files -z` lists of the app at `example`, by each file's
// path in the app. NUL-ended records hold each path as it is: git
// quotes nothing in them.
export const listedIn = (output, example) => output.split("\0").filter((path) => path.startsWith(`${example}/`)).map((path) => path.slice(example.length + 1));

// What `git status --porcelain=v1 -z` says changed in the app at
// `example`, by each file's path in the app. A rename or a copy is two
// paths, the new one first; it changed the app if either is in it.
export function changedIn(output, example) {
  const records = output.split("\0");
  const paths = [];
  for (let at = 0; at < records.length; at++) {
    const record = records[at];
    if (!record) continue;
    paths.push(record.slice(3));
    // Either column can say so: git marks a rename staged in the index
    // in the first and one found in the worktree in the second.
    if (/[RC]/.test(record.slice(0, 2))) paths.push(records[++at]);
  }
  return listedIn(paths.join("\0"), example);
}

// A demo's source, as data for its editor: each QML and TypeScript file
// its UPSTREAM.json pins, with its highlighting (`colour(code, lang)`).
export function projectOf(root, colour) {
  const upstream = JSON.parse(readFileSync(join(root, "UPSTREAM.json"), "utf8"));
  const text = Object.keys(upstream.files).filter((path) => /\.(qml|ts)$/.test(path));
  return {
    commit: upstream.commit,
    files: text.map((path) => {
      const code = readFileSync(join(root, path), "utf8");
      const lang = path.endsWith(".ts") ? "ts" : "qml";
      return { path, lang, code, rich: colour(code, lang) };
    }),
  };
}
// bundle/Demos/pro-later.js: each demo's app and project, imported only
// when its page asks. A module the compiler can follow names each file
// it imports outright, so the table is written out as code.
export function loaders(all) {
  const cases = (file) => all.map((demo) => `        case ${JSON.stringify(demo.name)}: return import(${JSON.stringify(`./${file(demo)}`)});`).join("\n");
  return `.pragma library
// Generated by site-ljos/scripts/build.mjs from Demos/pro.json (see
// scripts/pro.mjs); do not edit by hand. Each pro demo's app and its
// files for the editor, imported when its page asks, so no other page
// loads them.

function app(name) {
    switch (name) {
${cases((demo) => demo.app)}
    }
    throw new Error("no pro demo " + name);
}

function project(name) {
    switch (name) {
${cases((demo) => `${demo.name}-project.json`)}
    }
    throw new Error("no pro demo " + name);
}
`;
}
